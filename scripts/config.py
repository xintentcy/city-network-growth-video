def _ff(name='ffmpeg'):
    for cand in (os.environ.get(name.upper()),
                 shutil.which(name),
                 r'D:\soft\ffmpeg\ffmpeg-20200315-c467328-win64-static\bin\%s.exe' % name):
        if cand and os.path.exists(cand):
            return cand
    return name

